    protected override ConcreteSyntaxTree CreateModule(ModuleDefinition module, string moduleName, bool isDefault,
      ModuleDefinition externModule,
      string libraryName /*?*/, Attributes moduleAttributes, ConcreteSyntaxTree wr) {
      // Each Dafny module becomes one Huff source file.
      var safeName = PublicIdProtect(moduleName);
      if (string.IsNullOrEmpty(safeName)) {
        safeName = "_default";
      }
      var file = wr.NewFile($"{safeName}.huff");
      file.WriteLine("/* ============================================================");
      file.WriteLine(" *  Generated by the Dafny EVM (Huff) backend  [experimental]");
      file.WriteLine($" *  Dafny module : {moduleName}");
      file.WriteLine(" * ============================================================ */");
      file.WriteLine();
      return file;
    }

