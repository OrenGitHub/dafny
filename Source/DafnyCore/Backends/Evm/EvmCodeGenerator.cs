    // -----------------------------------------------------------------------
    //  EvmClassWriter: assembles the Huff representation of one Dafny class.
    //
    //  Emission layout (top-down inside the parent writer):
    //     [constantsSection]   // one `#define constant <NAME>_SLOT = 0x..`
    //     [methodsSection]     // one `#define macro <NAME>()` per method
    //     [dispatcher]         // final `#define macro MAIN()` with selector
    //                          //   jumps, written in Finish()
    // -----------------------------------------------------------------------
    private class EvmClassWriter : IClassWriter {
      private readonly EvmCodeGenerator parent;
      private readonly string className;
      private readonly ConcreteSyntaxTree wr;
      private readonly ConcreteSyntaxTree constantsSection;
      private readonly ConcreteSyntaxTree methodsSection;
      private readonly List<string> macroNames = new();
      private int nextSlot;

      public EvmClassWriter(EvmCodeGenerator parent, string className, ConcreteSyntaxTree wr) {
        this.parent = parent;
        this.className = className;
        this.wr = wr;
        // Reserve two in-order placeholders so DeclareField / CreateMethod
        // can write into them regardless of the order the base class visits
        // class members. MAIN() is appended directly to `wr` in Finish().
        this.constantsSection = wr.Fork();
        wr.WriteLine();
        this.methodsSection = wr.Fork();
        wr.WriteLine();
      }

      public void DeclareField(string name, TopLevelDecl enclosingDecl, bool isStatic, bool isConst,
          Type type, IOrigin tok, string rhs, Field /*?*/ field) {
        var slotName = parent.PublicIdProtect(name).ToUpperInvariant() + "_SLOT";
        constantsSection.WriteLine($"#define constant {slotName} = 0x{nextSlot:x2}");
        nextSlot++;
      }

      public ConcreteSyntaxTree CreateMethod(MethodOrConstructor m, List<TypeArgumentInstantiation> typeArgs,
          bool createBody, bool forBodyInheritance, bool lookasideBody) {
        var macroName = parent.PublicIdProtect(m.Name).ToUpperInvariant();
        macroNames.Add(macroName);
        methodsSection.WriteLine($"#define macro {macroName}() = takes(0) returns(0) {{");
        var body = methodsSection.Fork();
        methodsSection.WriteLine("}");
        methodsSection.WriteLine();
        if (!createBody) {
          body.WriteLine("    0x00 0x00 revert   // method body not supplied (abstract)");
          return null;
        }
        // The base class will fill `body` by invoking our Emit* overrides.
        // Those are still stubs, so this is the current frontier.
        return body;
      }

      public ConcreteSyntaxTree CreateFunction(string name, List<TypeArgumentInstantiation> typeArgs,
          List<Formal> formals, Type resultType, IOrigin tok, bool isStatic, bool createBody,
          MemberDecl member, bool forBodyInheritance, bool lookasideBody) {
        // Dafny functions and methods both lower to Huff macros in the MVP.
        var macroName = parent.PublicIdProtect(name).ToUpperInvariant();
        macroNames.Add(macroName);
        methodsSection.WriteLine($"#define macro {macroName}() = takes(0) returns(0) {{");
        var body = methodsSection.Fork();
        methodsSection.WriteLine("}");
        methodsSection.WriteLine();
        return createBody ? body : null;
      }

      public void Finish() {
        wr.WriteLine("/* --------- Dispatcher --------- */");
        wr.WriteLine("#define macro MAIN() = takes(0) returns(0) {");
        wr.WriteLine("    0x00 calldataload 0xe0 shr          // 4-byte function selector");
        foreach (var name in macroNames) {
          var sig = $"{name.ToLowerInvariant()}()";
          wr.WriteLine($"    dup1 __FUNC_SIG(\"{sig}\") eq {name.ToLowerInvariant()}_jump jumpi");
        }
        wr.WriteLine("    0x00 0x00 revert                    // unknown selector");
        foreach (var name in macroNames) {
          wr.WriteLine($"    {name.ToLowerInvariant()}_jump: {name}()");
        }
        wr.WriteLine("}");
      }

      public ConcreteSyntaxTree SynthesizeMethod(Method m, List<TypeArgumentInstantiation> typeArgs,
          bool createBody, bool forBodyInheritance, bool lookasideBody) {
